#!/usr/bin/env python3
"""Regenerates crates/app/src/embedded.rs from crates/app/assets/engine and catalog/flowseal."""
import hashlib, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
assets = os.path.join(root, "crates/app/assets/engine")
out = os.path.join(root, "crates/app/src/embedded.rs")
files = []
for base, _, names in os.walk(assets):
    for n in names:
        full = os.path.join(base, n)
        rel = os.path.relpath(full, assets).replace(os.sep, "/")
        if rel == "FLOWSEAL_LICENSE.txt":
            continue
        files.append((rel, hashlib.sha256(open(full, "rb").read()).hexdigest()))
files.sort()
winws = dict(files)["winws.exe"]
snaps = sorted(f for f in os.listdir(os.path.join(root, "catalog/flowseal")) if f.endswith(".toml"))
lines = ["// @generated by tools/gen_embedded.py - do not edit.",
         "// Source: Flowseal/zapret-discord-youtube commit 176f56dc3f11ce5915c26abcdde903f93d835b64.", "",
         "pub struct EmbeddedFile {", "    pub path: &'static str,", "    pub sha256: &'static str,",
         "    pub bytes: &'static [u8],", "}", "",
         'pub const ENGINE_ID: &str = "flowseal-176f56d";',
         f'pub const WINWS_SHA256: &str = "{winws}";', "",
         "pub static ENGINE_FILES: &[EmbeddedFile] = &["]
for rel, h in files:
    lines += ["    EmbeddedFile {", f'        path: "{rel}",', f'        sha256: "{h}",',
              f'        bytes: include_bytes!("../assets/engine/{rel}"),', "    },"]
lines += ["];", "", "pub static SNAPSHOTS: &[(&str, &str)] = &["]
for s in snaps:
    lines.append(f'    ("{s}", include_str!("../../../catalog/flowseal/{s}")),')
lines.append("];")
open(out, "w").write("\n".join(lines) + "\n")
print(len(files), "files,", len(snaps), "snapshots, winws", winws)
